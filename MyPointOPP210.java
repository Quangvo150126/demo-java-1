public class MyPointOPP210 {
    private int x;
    private int y;

    public MyPointOPP210(int x, int y) {
        this.x = x;
        this.y = y;
    }

    public int getX() {
        return x;
    }

    public int getY() {
        return y;
    }


    public String toString() {
        return "(" + x + ", " + y + ")";
    }
}
